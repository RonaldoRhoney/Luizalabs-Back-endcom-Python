# Verifica se um objeto está presento numa sequencia
frutas = ['banana', 'laranja', 'uva']   
curso = 'Python para Iniciantes'

print('banana' not in frutas)  # False
print('maçã' not in frutas)    # True
print('Python' not in curso)   # False
print('Java' not in curso)     # True
print('maçã' in frutas)    # False
print('Python' in curso)   # True
print('Java' in curso)     # False      
