
# Compara dois valores e retorna o maior deles
produto_01 = 10
produto_02 = 2

print(produto_01 > produto_02)  # Maior que
print(produto_01 < produto_02)  # Menor que
print(produto_01 >= produto_02)  # Maior ou igual a
print(produto_01 <= produto_02)  # Menor ou igual a
print(produto_01 == produto_02)  # Igual a
print(produto_01 != produto_02)  # Diferente de
