# DEfinem o valor inicial ou sobrepõe o valor de uma variável
saldo = 1000
print(saldo)
saldo = 2000
print(saldo)
# Atribuição composta
saldo += 500  # saldo = saldo + 500
print(saldo)
saldo -= 200  # saldo = saldo - 200
print(saldo)
saldo *= 2  # saldo = saldo * 2
print(saldo)
saldo /= 4  # saldo = saldo / 4
print(saldo)
saldo **= 2  # saldo = saldo ** 2
print(saldo)
saldo //= 3  # saldo = saldo // 3
print(saldo)
saldo %= 7  # saldo = saldo % 7
print(saldo)
